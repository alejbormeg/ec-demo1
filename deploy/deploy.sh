#!/usr/bin/env bash
# Deploys the whole demo to a Kubernetes cluster, from nothing.
#
#   ./deploy/deploy.sh
#
# Idempotent: every step is an upgrade-or-install, so re-running it after editing anything under
# deploy/ converges the cluster rather than complaining. Passwords are generated once, on the
# first run, and kept in deploy/.secrets/credentials.env (git-ignored) so a second run does not
# invalidate the ones already stored in the cluster.
#
# What it does NOT do, because both are outside the cluster:
#   • build the eight images this repository owns — see build-images.sh
#   • create the DNS records — ec1 and *.ec1 must resolve to the ingress controller's
#     LoadBalancer address before Let's Encrypt can issue anything. The wildcard is what makes
#     console.ec1 work without a new record; it still needs its own certificate, which
#     cert-manager issues on the first request once the name resolves.
set -euo pipefail
cd "$(dirname "$0")/.."

NS=ec-demo1
OBS_NS=observability
SECRETS=deploy/.secrets/credentials.env

echo "══ 1/6  Cluster prerequisites: ingress controller and certificate issuer ══"
helm repo add ingress-nginx https://kubernetes.github.io/ingress-nginx >/dev/null 2>&1 || true
helm repo add jetstack https://charts.jetstack.io >/dev/null 2>&1 || true
helm repo add grafana https://grafana.github.io/helm-charts >/dev/null 2>&1 || true
helm repo add prometheus-community https://prometheus-community.github.io/helm-charts >/dev/null 2>&1 || true
helm repo update >/dev/null

helm upgrade --install ingress-nginx ingress-nginx/ingress-nginx \
  -n ingress-nginx --create-namespace \
  --set controller.replicaCount=1 \
  --set controller.nodeSelector."kubernetes\.io/arch"=amd64 \
  --set controller.nodeSelector."topology\.kubernetes\.io/region"=hel1 \
  --set-string controller.podAnnotations."karpenter\.sh/do-not-disrupt"=true \
  --set controller.service.type=LoadBalancer \
  --set controller.resources.requests.cpu=100m \
  --set controller.resources.requests.memory=256Mi \
  --set controller.admissionWebhooks.patch.nodeSelector."kubernetes\.io/arch"=amd64 \
  --set defaultBackend.enabled=false \
  --wait --timeout 10m

helm upgrade --install cert-manager jetstack/cert-manager \
  -n cert-manager --create-namespace \
  --set crds.enabled=true \
  --set nodeSelector."kubernetes\.io/arch"=amd64 \
  --set webhook.nodeSelector."kubernetes\.io/arch"=amd64 \
  --set cainjector.nodeSelector."kubernetes\.io/arch"=amd64 \
  --wait --timeout 10m

echo
echo "── LoadBalancer address (the DNS records must point here) ──"
kubectl get svc -n ingress-nginx ingress-nginx-controller \
  -o jsonpath='{.status.loadBalancer.ingress[*].ip}{"\n"}'

echo "══ 2/6  Namespaces and secrets ══"
kubectl apply -f deploy/manifests/00-namespace.yaml
# inotify limits on every node (a DaemonSet in kube-system).
kubectl apply -f deploy/manifests/01-node-sysctl.yaml
kubectl create namespace "$OBS_NS" --dry-run=client -o yaml | kubectl apply -f -

# Generated once and reused: regenerating on every run would rotate the password the running
# PostgreSQL still expects, and the engine would fail to authenticate against its own database.
if [ ! -f "$SECRETS" ]; then
  mkdir -p deploy/.secrets
  {
    echo "# Generated by deploy.sh. Not in version control."
    echo "EC_POSTGRES_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
    echo "KEYCLOAK_ADMIN_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
    echo "GRAFANA_ADMIN_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
    echo "KAFKA_CONSOLE_PASSWORD=$(openssl rand -base64 18 | tr -d '/+=' | head -c 20)"
    echo "GIT_WEBHOOK_SECRET=$(openssl rand -hex 24)"
    echo "CP_POSTGRES_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
    # AES-256 for the control plane's stored LLM credentials. 32 bytes, base64, and it must not
    # be regenerated: nothing re-wraps the stored ciphertext, so a new key makes every catalogued
    # credential undecryptable and they have to be entered again.
    echo "CP_CRYPTO_KEY=$(openssl rand -base64 32)"
    echo "# Not generated: paste an Anthropic API key here to enable the console's chat panel."
    echo "# ANTHROPIC_API_KEY="
    echo "# Not generated: paste a Gmail App Password (Workspace account miguel@mateu.io) so Keycloak"
    echo "# can send mail through the postfix relay — e.g. a new user's set-password link. Requires"
    echo "# 2-Step Verification on the account; a normal password will not work over SMTP."
    echo "# POSTFIX_RELAY_PASSWORD="
    echo "# GitOps for the IA control plane. The webhook secret is generated; the GitHub read token"
    echo "# is pasted. Both only matter once GITOPS_ENABLED=true and GITOPS_REPO name a repo in"
    echo "# deploy/manifests/71-ia-control-plane.yaml."
    echo "GITOPS_WEBHOOK_SECRET=$(openssl rand -hex 24)"
    echo "# GITOPS_GITHUB_TOKEN="
  } > "$SECRETS"
  chmod 600 "$SECRETS"
  echo "generated $SECRETS"
fi
# Keys added after a deployment already exists would otherwise never be generated: the block
# above only runs on the very first deploy, and `set -u` then aborts on the first unbound one.
# Appending the missing ones keeps a re-run against an existing cluster working, and leaves every
# password already stored in that cluster exactly as it was.
append_if_missing() {  # name, value
  if ! grep -q "^$1=" "$SECRETS"; then
    echo "$1=$2" >> "$SECRETS"
    echo "added $1 to $SECRETS"
  fi
}
append_if_missing CP_POSTGRES_PASSWORD "$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
append_if_missing GITOPS_WEBHOOK_SECRET "$(openssl rand -hex 24)"
# Regenerating this one would make every stored LLM credential undecryptable — nothing re-wraps
# them — so it is written once and then left alone, like the PostgreSQL password above.
append_if_missing CP_CRYPTO_KEY "$(openssl rand -base64 32)"
# The same rule for the key the integrations' Opera secrets are sealed under: a new one leaves every
# stored connection unreadable, and each hotel's secret would have to be entered again.
append_if_missing INTEGRATIONS_CRYPTO_KEY "$(openssl rand -base64 32)"
# The documentation site's password (doc.ec1.mateu.io, user `riu`), for the docs-basic-auth Secret below.
append_if_missing DOCS_PASSWORD "$(openssl rand -base64 18 | tr -d '/+=' | head -c 20)"
# The demo user's password (realm ec-demo1). Only read when the realm is first imported: changing it
# here later does not change it in a running Keycloak — use kcadm.sh set-password for that.
append_if_missing DEMO_PASSWORD "$(openssl rand -base64 18 | tr -d '/+=' | head -c 20)"
append_if_missing DOCS_ORACLE_PASSWORD "$(openssl rand -base64 18 | tr -d '/+=' | head -c 20)"
# The AI agents' read-only login (agent_reader): it reads each service's agent views and nothing
# else (supporting/agent-sql, doc/src/content/docs/ia/datos-del-agente.md). Rotating it only needs the db-init Job re-run.
append_if_missing AGENT_DB_PASSWORD "$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)"
# What the front office signs its invoice and receipt links with. Without one each pod start draws
# its own key, and every link already e-mailed or printed stops opening at the next restart; kept
# once, like the crypto keys above, because rotating it breaks those links the same way.
append_if_missing FRONT_OFFICE_LINK_SECRET "$(openssl rand -base64 32)"

# shellcheck disable=SC1090
set -a; . "$SECRETS"; set +a

kubectl create secret generic ec-postgres -n "$NS" \
  --from-literal=POSTGRES_DB=workflow \
  --from-literal=POSTGRES_USER=workflow \
  --from-literal=POSTGRES_PASSWORD="$EC_POSTGRES_PASSWORD" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic ec-agent-reader -n "$NS" \
  --from-literal=AGENT_DB_USERNAME=agent_reader \
  --from-literal=AGENT_DB_PASSWORD="$AGENT_DB_PASSWORD" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic keycloak-admin -n "$NS" \
  --from-literal=password="$KEYCLOAK_ADMIN_PASSWORD" \
  --from-literal=demo-password="$DEMO_PASSWORD" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic grafana-admin -n "$OBS_NS" \
  --from-literal=admin-user=admin \
  --from-literal=admin-password="$GRAFANA_ADMIN_PASSWORD" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create configmap keycloak-realm -n "$NS" \
  --from-file=ec-demo1-realm.json=deploy/keycloak/ec-demo1-realm.json \
  --dry-run=client -o yaml | kubectl apply -f -
# htpasswd for the Kafka console's ingress. openssl's apr1 is the format nginx expects, and needs
# no apache2-utils on whoever runs this.
kubectl create secret generic kafka-console-auth -n "$NS" \
  --from-literal=auth="admin:$(openssl passwd -apr1 "$KAFKA_CONSOLE_PASSWORD")" \
  --dry-run=client -o yaml | kubectl apply -f -
# htpasswd for the documentation site's ingress (81-docs.yaml): `riu`, and `oracle` for Oracle's
# people. Each user's line is added only if it is not there: a bcrypt line is salted, so re-creating
# it on every run would change the Secret for nothing. bcrypt with apache2-utils' htpasswd, or from
# the httpd image when it is not installed; openssl's apr1 (what the Kafka console's uses, which
# ingress-nginx also takes) as the last resort.
docs_htpasswd() {  # <user> <password>
  if command -v htpasswd >/dev/null 2>&1; then htpasswd -nbB "$1" "$2"
  elif command -v docker >/dev/null 2>&1; then docker run --rm httpd:2.4-alpine htpasswd -nbB "$1" "$2"
  else echo "$1:$(openssl passwd -apr1 "$2")"
  fi | grep -v '^$'
}
DOCS_AUTH="$(kubectl get secret docs-basic-auth -n "$NS" -o jsonpath='{.data.auth}' 2>/dev/null | base64 -d || true)"
DOCS_AUTH_BEFORE="$DOCS_AUTH"
for docs_user in "riu:$DOCS_PASSWORD" "oracle:$DOCS_ORACLE_PASSWORD"; do
  if ! printf '%s\n' "$DOCS_AUTH" | grep -q "^${docs_user%%:*}:"; then
    DOCS_AUTH="$(printf '%s\n%s' "$DOCS_AUTH" "$(docs_htpasswd "${docs_user%%:*}" "${docs_user#*:}")" | grep -v '^$')"
  fi
done
if [ "$DOCS_AUTH" != "$DOCS_AUTH_BEFORE" ]; then
  kubectl create secret generic docs-basic-auth -n "$NS" --from-literal=auth="$DOCS_AUTH" \
    --dry-run=client -o yaml | kubectl apply -f -
fi
# Shared by the orchestrator and the forms engine: each reads its own key and ignores the other.
# Both apps verify inbound webhooks against it, and a blank value would make them verify nothing.
kubectl create secret generic ec-git-webhook -n "$NS" \
  --from-literal=WORKFLOW_GITIMPORT_WEBHOOKSECRET="$GIT_WEBHOOK_SECRET" \
  --from-literal=FORMS_GITIMPORT_WEBHOOKSECRET="$GIT_WEBHOOK_SECRET" \
  --dry-run=client -o yaml | kubectl apply -f -
# The control plane's own database and the key its credentials are encrypted with. Both are
# generated, unlike the Anthropic key, because both are derived rather than bought.
kubectl create secret generic ec-cp-postgres -n "$NS" \
  --from-literal=POSTGRES_DB=controlplane \
  --from-literal=POSTGRES_USER=controlplane \
  --from-literal=POSTGRES_PASSWORD="$CP_POSTGRES_PASSWORD" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic ec-cp-crypto -n "$NS" \
  --from-literal=CP_CRYPTO_KEY="$CP_CRYPTO_KEY" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic ec-integrations-crypto -n "$NS" \
  --from-literal=INTEGRATIONS_CRYPTO_KEY="$INTEGRATIONS_CRYPTO_KEY" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl create secret generic ec-front-office-links -n "$NS" \
  --from-literal=LINK_SECRET="$FRONT_OFFICE_LINK_SECRET" \
  --dry-run=client -o yaml | kubectl apply -f -

# The chat agent's Anthropic key. Not generated — it is bought, not derived — so it is only
# created when ANTHROPIC_API_KEY is in the environment or in credentials.env, which is also why
# the deployment marks it optional. Without it the agent still starts and logs why, and the first
# prompt fails with a 401 from Anthropic; every other part of the console is unaffected.
if [ -n "${ANTHROPIC_API_KEY:-}" ]; then
  kubectl create secret generic ec-anthropic -n "$NS" \
    --from-literal=ANTHROPIC_API_KEY="$ANTHROPIC_API_KEY" \
    --dry-run=client -o yaml | kubectl apply -f -
else
  echo "ANTHROPIC_API_KEY not set — skipping the ec-anthropic secret."
  echo "  The chat panel will answer with a 401 until you add it to $SECRETS and re-run this."
fi

# The customer MDM's connection to Salesforce (docs/poc-acl, H11): the org's External Client App,
# client credentials. Bought, not derived, like the Anthropic key — created only when present. Without
# it the MDM still resolves identities for the connector; projecting to Salesforce and hearing its
# merges wait until the secret exists and the pod restarts.
if [ -n "${SF_CLIENT_ID:-}" ] && [ -n "${SF_CLIENT_SECRET:-}" ] && [ -n "${SF_DOMAIN:-}" ]; then
  kubectl create secret generic ec-salesforce -n "$NS" \
