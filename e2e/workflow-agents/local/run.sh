#!/usr/bin/env bash
set -euo pipefail
LOCAL_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(cd -- "$LOCAL_DIR/../../.." && pwd)"

usage() {
  cat <<'HELP'
Usage: run.sh prepare|build [--jars-only]|up [--skip-build]|check|restart-worker|status|logs|down|reset

prepare  Generate synthetic inputs and private local credentials, without Docker.
build    Build branch jars and local images. --jars-only does not contact Docker.
up       Start isolated dependencies, wait for GitOps publication, then start engine.
check    Run the synthetic happy-path and uncertain-effect/restart acceptance checks.
down     Stop only this Compose project, preserving its data and credentials.
reset    Remove only this project's disposable volumes and generated state.

Optional checkout overrides: ENGINE_REPO, IA_CONFIG_REPO, DEFINITIONS_REPO.
Maven cache: MAVEN_REPO_LOCAL (default /tmp/ec-workflow-agent-m2).
HELP
}

prepare() {
  python3 "$LOCAL_DIR/prepare.py"
  # Values are generated by prepare.py, never copied from existing demo credentials.
  set -a
  source "$LOCAL_DIR/.env"
  set +a
}

compose() {
  docker compose --project-name ec-workflow-agent-local --env-file "$LOCAL_DIR/.env" \
    --file "$LOCAL_DIR/compose.yaml" "$@"
}

build_jars() {
  local cache="${MAVEN_REPO_LOCAL:-/tmp/ec-workflow-agent-m2}"
  local -a mvn_args=(-B -ntp "-Dmaven.repo.local=$cache" -DskipTests)
  # Minimal JRE distributions can include jdk.compiler but omit ct.sym. Its absence
  # prevents --release from working, while source/target 21 still compile these jars.
  local java_home
  java_home="$(java -XshowSettings:properties -version 2>&1 | sed -n 's/^[[:space:]]*java.home = //p')"
  if [[ ! -f "$java_home/lib/ct.sym" ]]; then
    mvn_args+=(-Dmaven.compiler.release= -Dmaven.compiler.source=21 -Dmaven.compiler.target=21)
  fi
  mvn "${mvn_args[@]}" -f "$ENGINE_REPO/pom.xml" -pl modules/workflow-engine -am install
  mvn "${mvn_args[@]}" -f "$ENGINE_REPO/apps/orchestrator-standalone-app/pom.xml" package
  mvn "${mvn_args[@]}" -f "$DEMO_DIR/supporting/ui-commons/pom.xml" install
  mvn "${mvn_args[@]}" -f "$DEMO_DIR/ai/ia-control-plane/pom.xml" package
  mvn "${mvn_args[@]}" -f "$DEMO_DIR/ai/ia-agent/pom.xml" package
  mkdir -p "$LOCAL_STATE_DIR/jars"
  cp "$ENGINE_REPO/apps/orchestrator-standalone-app/target/orchestrator-standalone-app-0.0.1-SNAPSHOT.jar" "$LOCAL_STATE_DIR/jars/orchestrator.jar"
  cp "$DEMO_DIR/ai/ia-control-plane/target/ia-control-plane-0.1.0.jar" "$LOCAL_STATE_DIR/jars/ia-control-plane.jar"
  cp "$DEMO_DIR/ai/ia-agent/target/ia-agent-0.1.0.jar" "$LOCAL_STATE_DIR/jars/ia-agent.jar"
  python3 - "$LOCAL_STATE_DIR/jars" <<'PY'
import hashlib
import json
from pathlib import Path
import sys
directory = Path(sys.argv[1])
manifest = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(directory.glob("*.jar"))}
(directory.parent / "jars.json").write_text(json.dumps(manifest, indent=2) + "\n")
print("Prepared three branch-built application jars; digests saved to jars.json.")
PY
}

command="${1:-help}"
shift || true
case "$command" in
  help|--help|-h) usage ;;
  prepare) prepare ;;
  build)
    [[ $# -eq 0 || ( $# -eq 1 && "$1" == --jars-only ) ]] || { usage; exit 2; }
    prepare
    build_jars
    if [[ "${1:-}" != --jars-only ]]; then compose build; fi
    ;;
  up)
    [[ $# -eq 0 || ( $# -eq 1 && "$1" == --skip-build ) ]] || { usage; exit 2; }
    prepare
    if [[ "${1:-}" != --skip-build ]]; then build_jars; compose build; fi
    for jar in orchestrator ia-control-plane ia-agent; do
      [[ -s "$LOCAL_STATE_DIR/jars/$jar.jar" ]] || { echo "Missing branch jar: $jar; run build first." >&2; exit 1; }
    done
    compose config --quiet
    compose up --detach engine-db catalogue-db redpanda keycloak fixtures ia-control-plane ia-workflow-worker
    python3 "$LOCAL_DIR/acceptance.py" --state-dir "$LOCAL_STATE_DIR" --wait-catalogue
    compose up --detach orchestrator
    python3 "$LOCAL_DIR/acceptance.py" --state-dir "$LOCAL_STATE_DIR"
    ;;
  check)
    prepare
    python3 "$LOCAL_DIR/acceptance.py" --state-dir "$LOCAL_STATE_DIR" "$@"
    ;;
  restart-worker)
    prepare
    compose restart ia-workflow-worker
    ;;
  status|logs|down)
    [[ -f "$LOCAL_DIR/.env" ]] || { echo "No prepared local project." >&2; exit 1; }
    if [[ "$command" == status ]]; then compose ps;
    elif [[ "$command" == logs ]]; then compose logs --tail=100 "$@";
    else compose down "$@"; fi
    ;;
  reset)
    if [[ -f "$LOCAL_DIR/.env" ]]; then compose down --volumes --remove-orphans; fi
    rm -rf -- "$LOCAL_DIR/.state"
    rm -f -- "$LOCAL_DIR/.env"
    ;;
  *) usage; exit 2 ;;
esac
